import pytest

from apiroute.codegen.openapi.openapi_reader import OpenApiReader
from apiroute.codegen.package_emitter import PackageEmitter
from tests.codegen.conftest import FIXTURES


def definition():
    return OpenApiReader(str(FIXTURES / "shop.yaml"), "ShopApi").read()


def test_layout():
    files = PackageEmitter(definition(), with_models=True).files()
    for path in (
        "__init__.py",
        "client.py",
        "pets/client.py",
        "models/client.py",
        "models/models.py",
        "pets/models/models.py",
        "store/models/schemas/order.py",
    ):
        assert path in files
    assert all(source.startswith("# Generated by apiroute") for source in files.values())
    assert not any("models" in path for path in PackageEmitter(definition(), False).files())


def test_output_is_deterministic():
    first = PackageEmitter(definition(), with_models=True).files()
    assert first == PackageEmitter(definition(), with_models=True).files()


def test_regenerating_removes_stale_files_but_keeps_yours(tmp_path):
    out = tmp_path / "shop"
    PackageEmitter(definition(), with_models=True).write(out)
    (out / "stale").mkdir()
    (out / "stale" / "client.py").write_text("# Generated by apiroute 0.0 from old.yaml.\n")
    (out / "notes.md").write_text("mine")
    PackageEmitter(definition(), with_models=False).write(out)
    assert not (out / "stale").exists()
    assert not (out / "models").exists()
    assert (out / "notes.md").read_text() == "mine"


def test_refuses_a_directory_it_did_not_generate(tmp_path):
    (tmp_path / "client.py").write_text("print('hand written')\n")
    with pytest.raises(FileExistsError, match="isn't a package apiroute generated"):
        PackageEmitter(definition(), with_models=False).write(tmp_path)


def test_a_level_without_models_has_a_typed_empty_all():
    definition = OpenApiReader(str(FIXTURES / "plain.yaml"), "PlainApi").read()
    index = PackageEmitter(definition, with_models=True).files()["models/models.py"]
    assert "__all__: list[str] = []\n" in index
