from apiroute.codegen.api_definition import ApiDefinition, Model, ModelField
from apiroute.codegen.import_order import import_names
from apiroute.codegen.model_modules import SchemaModule
from apiroute.codegen.python_literals import py_str
from apiroute.codegen.source_writer import SourceWriter

_HEADER = "# Generated by apiroute {version} from {source}. Do not edit: regenerate instead."

# defer_build: a model's validator is built on first use, not at import
# populate_by_name: fields can be set by their Python names as well as their wire names
_CONFIG = "ConfigDict(defer_build=True, populate_by_name=True, protected_namespaces=())"


class SchemaModuleEmitter:
    """Writes one models/schemas/<name>.py: a model (or a cycle of models that refer to each
    other), importing only the modules it depends on.

    Annotations are postponed and validators deferred, so importing it stays cheap. Aliases
    run at import, so they come after the classes and in dependency order."""

    def __init__(
        self,
        definition: ApiDefinition,
        module: SchemaModule,
        modules: dict[str, SchemaModule],
        dependencies,
        version: str,
    ):
        self._definition = definition
        self._module = module
        self._modules = modules
        self._dependencies = dependencies
        self._version = version

    def source(self) -> str:
        out = SourceWriter()
        out.line(_HEADER.format(version=self._version, source=self._definition.source))
        out.line("# ruff: noqa: E501  (generated names and Literal values can be long)")
        out.docstring(f"{', '.join(self._module.models)}.")
        out.line()
        out.line("from __future__ import annotations")
        sections = []
        typing_names = [n for n in ("Any", "Literal") if self._uses(n)]
        if typing_names:
            sections.append([f"from typing import {import_names(typing_names)}"])
        pydantic_names = ["BaseModel", "ConfigDict"] if self._classes() else []
        if any(field.alias for model in self._classes() for field in model.fields):
            pydantic_names.append("Field")
        if pydantic_names:
            sections.append([f"from pydantic import {import_names(pydantic_names)}"])
        dependencies = self._dependency_imports()
        if dependencies:
            sections.append(dependencies)
        for section in sections:
            out.line()
            out.lines(*section)
        out.line()
        out.line(f"__all__ = [{', '.join(py_str(name) for name in self._module.models)}]")
        for model in self._classes():
            out.lines("", "")
            self._model_class(out, model)
        aliases = self._aliases()
        if aliases:
            out.lines("", "")
        for model in aliases:
            if model.description:
                out.comment(model.description, max_lines=1)
            out.line(f"{model.name} = {model.alias_of.expr}")
        return out.text()

    def _models(self) -> list[Model]:
        return [self._definition.models[name] for name in self._module.models]

    def _classes(self) -> list[Model]:
        return [model for model in self._models() if model.alias_of is None]

    def _uses(self, name: str) -> bool:
        exprs = [m.alias_of.expr for m in self._models() if m.alias_of is not None]
        exprs += [f.type.expr for m in self._models() for f in m.fields]
        separators = str.maketrans("[],|", "    ")
        return any(name in expr.translate(separators).split() for expr in exprs)

    def _aliases(self) -> list[Model]:
        aliases = {m.name: m for m in self._models() if m.alias_of is not None}
        ordered: list[Model] = []
        visiting: set[str] = set()

        def visit(model: Model) -> None:
            if model in ordered or model.name in visiting:
                return
            visiting.add(model.name)
            for dependency in sorted(model.alias_of.models):
                if dependency in aliases:
                    visit(aliases[dependency])
            ordered.append(model)

        for name in sorted(aliases):
            visit(aliases[name])
        return ordered

    def _dependency_imports(self) -> list[str]:
        by_module: dict[str, set[str]] = {}
        for name in self._module.models:
            for dependency in self._dependencies(name):
                target = self._modules[dependency]
                if target is self._module:
                    continue
                by_module.setdefault(self._relative(target), set()).add(dependency)
        # ruff orders relative imports furthest first: more leading dots, then by name
        ordered = sorted(by_module, key=lambda p: (len(p.lstrip(".")) - len(p), p))
        return [f"from {path} import {import_names(by_module[path])}" for path in ordered]

    def _relative(self, target: SchemaModule) -> str:
        """From <folder>/models/schemas/: a sibling, or a root module from a tag's folder."""
        if target.folder == self._module.folder:
            return f".{target.name}"
        return f"....models.schemas.{target.name}"

    def _model_class(self, out: SourceWriter, model: Model) -> None:
        out.line(f"class {model.name}(BaseModel):")
        with out.indented():
            if model.description:
                out.docstring(model.description)
                out.line()
            out.line(f"model_config = {_CONFIG}")
            for field in model.fields:
                if field.description:
                    out.line()
                    out.comment(field.description, max_lines=3)
                out.line(_field(field))


def _field(field: ModelField) -> str:
    annotation = field.type.expr if field.required else field.type.optional().expr
    if field.alias is None:
        default = "" if field.required else " = None"
        return f"{field.name}: {annotation}{default}"
    if field.required:
        return f"{field.name}: {annotation} = Field(alias={py_str(field.alias)})"
    return f"{field.name}: {annotation} = Field(None, alias={py_str(field.alias)})"
